CREATE TABLE endereco (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_cadastro timestamp NOT NULL,
    data_alteracao timestamp,
    cliente_id bigint NOT NULL REFERENCES cliente(id) ON DELETE CASCADE,
    apelido varchar(60) NOT NULL CHECK (char_length(trim(apelido)) BETWEEN 1 AND 60),
    destinatario varchar(150) NOT NULL CHECK (char_length(trim(destinatario)) BETWEEN 2 AND 150),
    cep varchar(8) NOT NULL CHECK (cep ~ '^[0-9]{8}$'),
    logradouro varchar(200) NOT NULL CHECK (char_length(trim(logradouro)) > 0),
    bairro varchar(100) NOT NULL CHECK (char_length(trim(bairro)) > 0),
    numero varchar(20) NOT NULL CHECK (char_length(trim(numero)) > 0),
    complemento varchar(100),
    principal boolean NOT NULL DEFAULT false,
    municipio_id bigint NOT NULL REFERENCES municipio(id)
);

CREATE INDEX ix_endereco_cliente ON endereco(cliente_id);
CREATE INDEX ix_endereco_municipio ON endereco(municipio_id);
CREATE UNIQUE INDEX uk_endereco_cliente_principal ON endereco(cliente_id) WHERE principal = true;

INSERT INTO endereco (
    data_cadastro, data_alteracao, cliente_id, apelido, destinatario,
    cep, logradouro, bairro, numero, complemento, principal, municipio_id
)
SELECT
    c.data_cadastro, c.data_alteracao, c.id, 'Principal', c.nome,
    c.cep, c.logradouro, c.bairro, c.numero, c.complemento, true, c.municipio_id
FROM cliente c
WHERE NOT EXISTS (
    SELECT 1 FROM endereco e WHERE e.cliente_id = c.id
);

