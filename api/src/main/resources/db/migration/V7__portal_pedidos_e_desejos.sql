CREATE TABLE evento_pedido (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_cadastro timestamp NOT NULL, data_alteracao timestamp,
    pedido_id bigint NOT NULL REFERENCES pedido(id),
    status integer NOT NULL CHECK (status IN (1,2,3,4,5,6)),
    ocorrido_em timestamptz NOT NULL, descricao varchar(200) NOT NULL,
    responsavel_subject varchar(255)
);
CREATE INDEX ix_evento_pedido ON evento_pedido(pedido_id, ocorrido_em, id);
