CREATE TABLE pedido (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_cadastro timestamp NOT NULL, data_alteracao timestamp,
    cliente_id bigint NOT NULL REFERENCES cliente(id),
    chave_checkout uuid NOT NULL UNIQUE, requisicao_hash varchar(64) NOT NULL,
    status integer NOT NULL CHECK (status IN (1,2,3,4,5,6)),
    criado_em timestamptz NOT NULL, expira_em timestamptz NOT NULL CHECK (expira_em > criado_em),
    frete numeric(12,2) NOT NULL CHECK (frete >= 0),
    prazo_dias_uteis integer NOT NULL CHECK (prazo_dias_uteis > 0),
    entrega_destinatario varchar(150) NOT NULL, entrega_cep varchar(8) NOT NULL CHECK (entrega_cep ~ '^[0-9]{8}$'),
    entrega_logradouro varchar(200) NOT NULL, entrega_bairro varchar(100) NOT NULL,
    entrega_numero varchar(20) NOT NULL, entrega_complemento varchar(100),
    entrega_municipio varchar(150) NOT NULL, entrega_uf varchar(2) NOT NULL,
    versao bigint NOT NULL DEFAULT 0 CHECK (versao >= 0)
);
CREATE INDEX ix_pedido_cliente ON pedido(cliente_id, criado_em DESC);
CREATE INDEX ix_pedido_expiracao ON pedido(expira_em) WHERE status = 1;
CREATE TABLE item_pedido (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_cadastro timestamp NOT NULL, data_alteracao timestamp,
    pedido_id bigint NOT NULL REFERENCES pedido(id), mouse_id bigint NOT NULL REFERENCES mouse(id),
    sku varchar(50) NOT NULL, nome varchar(150) NOT NULL, marca varchar(100) NOT NULL, cor varchar(50) NOT NULL,
    quantidade integer NOT NULL CHECK (quantidade BETWEEN 1 AND 999),
    preco_unitario numeric(12,2) NOT NULL CHECK (preco_unitario > 0),
    UNIQUE(pedido_id, mouse_id)
);
CREATE INDEX ix_item_pedido_mouse ON item_pedido(mouse_id);
CREATE TABLE pagamento (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_cadastro timestamp NOT NULL, data_alteracao timestamp,
    pedido_id bigint NOT NULL REFERENCES pedido(id), chave_idempotencia uuid NOT NULL UNIQUE,
    forma integer NOT NULL CHECK (forma IN (1,2)), status integer NOT NULL CHECK (status IN (1,2,3,4)),
    resultado_simulado integer NOT NULL CHECK (resultado_simulado IN (1,2,3)),
    valor numeric(18,2) NOT NULL CHECK (valor > 0), processado_em timestamptz,
    versao bigint NOT NULL DEFAULT 0 CHECK (versao >= 0),
    CHECK ((status = 1 AND processado_em IS NULL) OR (status <> 1 AND processado_em IS NOT NULL))
);
CREATE INDEX ix_pagamento_pedido ON pagamento(pedido_id);
CREATE UNIQUE INDEX uk_pagamento_ativo ON pagamento(pedido_id) WHERE status IN (1,2);
