CREATE TABLE sensor (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_cadastro timestamp NOT NULL,
    data_alteracao timestamp,
    modelo varchar(100) NOT NULL UNIQUE CHECK (char_length(trim(modelo)) BETWEEN 2 AND 100),
    fabricante varchar(100) NOT NULL DEFAULT 'PixArt' CHECK (char_length(trim(fabricante)) BETWEEN 2 AND 100),
    dpi_maximo integer NOT NULL CHECK (dpi_maximo > 0),
    ips integer NOT NULL DEFAULT 400 CHECK (ips > 0),
    aceleracao_g integer NOT NULL DEFAULT 40 CHECK (aceleracao_g > 0),
    ativo boolean NOT NULL DEFAULT true,
    versao bigint NOT NULL DEFAULT 0 CHECK (versao >= 0)
);
CREATE UNIQUE INDEX uk_sensor_modelo_normalizado ON sensor (lower(modelo));

INSERT INTO sensor (data_cadastro, modelo, fabricante, dpi_maximo, ips, aceleracao_g, ativo, versao)
SELECT
    CURRENT_TIMESTAMP,
    trim(m.sensor),
    'Fabricante Padrão',
    GREATEST(MAX(m.dpi_maximo), 1),
    400,
    40,
    true,
    0
FROM mouse m
WHERE m.sensor IS NOT NULL AND char_length(trim(m.sensor)) >= 2
GROUP BY lower(trim(m.sensor)), trim(m.sensor)
ON CONFLICT DO NOTHING;

CREATE TABLE switch_mouse (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_cadastro timestamp NOT NULL,
    data_alteracao timestamp,
    modelo varchar(100) NOT NULL UNIQUE CHECK (char_length(trim(modelo)) BETWEEN 2 AND 100),
    fabricante varchar(100) NOT NULL DEFAULT 'Omron' CHECK (char_length(trim(fabricante)) BETWEEN 2 AND 100),
    tipo_switch integer NOT NULL CHECK (tipo_switch IN (1, 2)),
    durabilidade_milhoes_cliques integer NOT NULL DEFAULT 50 CHECK (durabilidade_milhoes_cliques > 0),
    forca_atuacao_gf numeric(5,1) CHECK (forca_atuacao_gf IS NULL OR forca_atuacao_gf > 0),
    ativo boolean NOT NULL DEFAULT true,
    versao bigint NOT NULL DEFAULT 0 CHECK (versao >= 0)
);
CREATE UNIQUE INDEX uk_switch_mouse_modelo_normalizado ON switch_mouse (lower(modelo));

INSERT INTO switch_mouse (
    data_cadastro, modelo, fabricante, tipo_switch, durabilidade_milhoes_cliques, ativo, versao
)
SELECT
    CURRENT_TIMESTAMP,
    trim(m.modelo_switch),
    'Fabricante Padrão',
    COALESCE(MAX(m.tipo_switch), 1),
    50,
    true,
    0
FROM mouse m
WHERE m.modelo_switch IS NOT NULL AND char_length(trim(m.modelo_switch)) >= 2
GROUP BY lower(trim(m.modelo_switch)), trim(m.modelo_switch)
ON CONFLICT DO NOTHING;

