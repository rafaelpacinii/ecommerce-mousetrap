CREATE TABLE transportadora (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_cadastro timestamp NOT NULL,
    data_alteracao timestamp,
    nome varchar(100) NOT NULL UNIQUE CHECK (char_length(trim(nome)) BETWEEN 2 AND 100),
    cnpj varchar(14) UNIQUE CHECK (cnpj IS NULL OR cnpj ~ '^[0-9]{14}$'),
    url_rastreio_padrao varchar(500),
    valor_base_frete numeric(12,2) NOT NULL DEFAULT 0.00 CHECK (valor_base_frete >= 0),
    prazo_medio_dias integer NOT NULL DEFAULT 5 CHECK (prazo_medio_dias > 0),
    ativo boolean NOT NULL DEFAULT true,
    versao bigint NOT NULL DEFAULT 0 CHECK (versao >= 0)
);
CREATE UNIQUE INDEX uk_transportadora_nome_normalizado ON transportadora (lower(nome));

INSERT INTO transportadora (data_cadastro, nome, valor_base_frete, prazo_medio_dias, ativo, versao)
SELECT
    CURRENT_TIMESTAMP,
    trim(p.transportadora),
    0.00,
    5,
    true,
    0
FROM pedido p
WHERE p.transportadora IS NOT NULL AND char_length(trim(p.transportadora)) >= 2
GROUP BY lower(trim(p.transportadora)), trim(p.transportadora)
ON CONFLICT DO NOTHING;

ALTER TABLE pedido ADD COLUMN transportadora_id bigint REFERENCES transportadora(id);
UPDATE pedido p
SET transportadora_id = t.id
FROM transportadora t
WHERE p.transportadora IS NOT NULL AND lower(trim(p.transportadora)) = lower(t.nome);
CREATE INDEX ix_pedido_transportadora ON pedido(transportadora_id);

