CREATE TABLE mouse_pegada (
    mouse_id bigint NOT NULL REFERENCES mouse(id) ON DELETE CASCADE,
    pegada integer NOT NULL CHECK (pegada IN (1, 2, 3)),
    PRIMARY KEY (mouse_id, pegada)
);

CREATE TABLE imagem_mouse (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_cadastro timestamp NOT NULL,
    data_alteracao timestamp,
    mouse_id bigint NOT NULL REFERENCES mouse(id) ON DELETE CASCADE,
    url varchar(2048) NOT NULL,
    texto_alternativo varchar(200) NOT NULL CHECK (char_length(trim(texto_alternativo)) BETWEEN 1 AND 200),
    ordem integer NOT NULL CHECK (ordem >= 0),
    CONSTRAINT uk_imagem_mouse_ordem UNIQUE (mouse_id, ordem)
);
